//! The pace-geojson core, as WebAssembly, for JavaScript to call.
//!
//! A thin shell over `pace-geojson` and nothing else: JSON in, JSON out, no
//! opinions of its own. The core crate stays free of `wasm-bindgen` so that it
//! remains an ordinary Rust library any other program can link — the binding is the part
//! that knows about JavaScript, and it is deliberately the only part.
//!
//! ## Why a harness runs both engines
//!
//! The corpus keeps two implementations honest *at rest*. This keeps them
//! honest *in motion*: every field a harness simulates is folded twice, by the
//! TypeScript and by this, and the answers compared (`ts/test/differential.test.ts`
//! is one such harness). A corpus case is a
//! disagreement somebody thought to write down; a simulated field is a
//! disagreement nobody thought of, generated by the thousand.
//!
//! When they differ, the harness says so and the difference becomes the next
//! conformance case.

use pace_geojson::{packs, run::run as answer};
use wasm_bindgen::prelude::*;

/// Fold a document and a log. Both are JSON; the answer is JSON:
/// `{"kind":"ran","states":[…]}` with every entrant's state as SPEC.md §4
/// encodes it, `{"kind":"refused","why":{unknown_version, missing_dialects,
/// refused, broken}}`, or `{"kind":"malformed","why":"…","broken":[…]}`.
///
/// Strings rather than `JsValue` structures on purpose: the wire between the
/// two implementations should be the same bytes the corpus is written in, or
/// the comparison is testing two serialisers rather than two folds.
#[wasm_bindgen]
pub fn run(document_json: &str, log_json: &str) -> String {
    serde_json::to_string(&answer(&packs::all(), document_json, log_json))
        .unwrap_or_else(|e| format!(r#"{{"kind":"malformed","why":"could not answer: {e}","broken":[]}}"#))
}

/// Which dialects this build understands, so a caller can say what it has.
#[wasm_bindgen]
pub fn dialects() -> String {
    let names: Vec<String> = packs::all().iter().map(pace_geojson::packs::Pack::dialect).collect();
    serde_json::to_string(&names).unwrap_or_else(|_| "[]".to_string())
}
